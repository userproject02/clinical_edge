import 'dart:typed_data';

import 'package:clinical_edge/core/money.dart';
import 'package:clinical_edge/core/payments/payment_gateway.dart';
import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;

/// Builds a simple one-page tax-invoice PDF (English; v1). Contains only
/// receipt fields: no card number beyond the last 4 digits in [method].
Future<Uint8List> buildReceiptPdf({
  required Order order,
  required String sellerName,
  required String sellerTrn,
  required String buyer,
  required String item,
  required String method,
  required String timestamp,
}) {
  final doc = pw.Document(title: 'Tax invoice ${order.invoiceNo ?? ''}');
  pw.Widget row(String label, String value, {bool bold = false}) => pw.Padding(
    padding: const pw.EdgeInsets.symmetric(vertical: 4),
    child: pw.Row(
      mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
      children: <pw.Widget>[
        pw.Text(label),
        pw.Text(
          value,
          style: bold
              ? const pw.TextStyle(fontWeight: pw.FontWeight.bold)
              : null,
        ),
      ],
    ),
  );
  doc.addPage(
    pw.Page(
      pageFormat: PdfPageFormat.a5,
      build: (context) => pw.Column(
        crossAxisAlignment: pw.CrossAxisAlignment.stretch,
        children: <pw.Widget>[
          pw.Text(
            'Tax invoice',
            style: const pw.TextStyle(
              fontSize: 20,
              fontWeight: pw.FontWeight.bold,
            ),
          ),
          pw.SizedBox(height: 4),
          pw.Text('${order.invoiceNo ?? ''} · $timestamp'),
          pw.SizedBox(height: 16),
          row('Seller', '$sellerName · TRN $sellerTrn'),
          row('Billed to', buyer),
          row('Item', item),
          row('Method', method),
          pw.Divider(),
          row('Subtotal', 'AED ${Money(order.subtotalFils).plain}'),
          row('VAT $vatPercent%', 'AED ${Money(order.vatFils).plain}'),
          row('Total paid', 'AED ${Money(order.totalFils).plain}', bold: true),
          pw.SizedBox(height: 24),
          pw.Text(
            'Demo receipt generated by ClinicalEdge (mock payment).',
            style: const pw.TextStyle(fontSize: 9, color: PdfColors.grey700),
          ),
        ],
      ),
    ),
  );
  return doc.save();
}
